#!/usr/bin/env python3
"""Refresh license metadata and the notices shipped in installed dependency packages."""

import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent


def output_json(arguments):
    return json.loads(subprocess.check_output(arguments, cwd=ROOT, text=True))


def license_files(directory):
    prefixes = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE", "COPYRIGHT")
    return sorted(
        path for path in directory.iterdir()
        if path.is_file() and path.name.upper().startswith(prefixes)
    )


def main():
    cargo = output_json(["cargo", "metadata", "--locked", "--format-version", "1"])
    records = []
    for package in cargo["packages"]:
        if not package["source"]:
            continue
        name, version = package["name"], package["version"]
        records.append({
            "ecosystem": "Rust", "name": name, "version": version,
            "license": package["license"],
            "source": f"https://crates.io/api/v1/crates/{name}/{version}/download",
            "directory": Path(package["manifest_path"]).parent,
        })

    javascript = {}
    for directory in (ROOT, ROOT / "ui"):
        licenses = output_json(["pnpm", "-C", str(directory), "licenses", "list", "--json"])
        for expression, packages in licenses.items():
            for package in packages:
                for path in package["paths"]:
                    base = Path(path)
                    metadata = json.loads((base / "package.json").read_text())
                    name, version = metadata["name"], metadata["version"]
                    javascript[(name, version)] = {
                        "ecosystem": "JavaScript / tooling", "name": name,
                        "version": version, "license": expression,
                        "source": f"https://www.npmjs.com/package/{name}/v/{version}",
                        "directory": base,
                    }
    records.extend(javascript.values())
    records.sort(key=lambda record: (record["ecosystem"], record["name"], record["version"]))

    notices = {}
    for record in records:
        record["notices"] = []
        for path in license_files(record["directory"]):
            content = path.read_text(errors="replace").strip()
            digest = hashlib.sha256(content.encode()).hexdigest()[:16]
            entry = notices.setdefault(digest, {"text": content, "packages": []})
            entry["packages"].append(f"{record['name']} {record['version']} / {path.name}")
            record["notices"].append(digest)

    lines = [
        "# Third-party dependency licenses", "",
        "Generated by `python3 scripts/update-licenses.py` after `cargo fetch --locked`",
        "and `pnpm install --frozen-lockfile`. Covers the locked Cargo graph (all",
        "platforms) and installed pnpm dependencies, including build/test tooling.", "",
        "License expressions are preserved. For OR expressions, use the permissive",
        "MIT/Apache/BSD/Zlib alternative; LGPL alternatives are not selected. AND",
        "expressions retain all obligations. Unicode-3.0, ISC and MPL-2.0 retain their",
        "own terms. No dependency source has been modified in this skeleton.", "",
        "MPL-2.0 components are combined as separate files in a larger Apache-2.0 work;",
        "they are not relicensed. Their exact, unmodified source is available through",
        "the source links below, under MPL-2.0. See the",
        "[Mozilla FAQ, Q8 and Q13](https://www.mozilla.org/en-US/MPL/2.0/FAQ/).", "",
        "Original license/notice files included in installed packages follow the",
        "inventory. Some upstream packages omit standalone notice files from their",
        "published archives; their license metadata and exact source links are retained.",
        "System WebView/OS libraries and locally installed toolchains are not vendored.", "",
    ]
    for ecosystem in ("Rust", "JavaScript / tooling"):
        lines.extend([
            f"## {ecosystem}", "",
            "| Package | Version | License | Source | Bundled notices |",
            "| --- | --- | --- | --- | --- |",
        ])
        for record in records:
            if record["ecosystem"] != ecosystem:
                continue
            links = ", ".join(f"[{digest}](#notice-{digest})" for digest in record["notices"])
            lines.append(
                f"| {record['name']} | {record['version']} | {record['license']} | "
                f"[source]({record['source']}) | {links or 'See upstream source'} |"
            )
        lines.append("")

    lines.extend(["## Original dependency notices", ""])
    for digest, entry in sorted(notices.items()):
        lines.extend([
            f"### Notice {digest}", "",
            "; ".join(sorted(set(entry["packages"]))), "", "````text",
            entry["text"], "````", "",
        ])
    (ROOT / "docs/third-party-licenses.md").write_text("\n".join(lines))
    print(f"Recorded {len(records)} dependencies and {len(notices)} unique notice texts.")


if __name__ == "__main__":
    main()
